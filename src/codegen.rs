//! The code a checker's `build.rs` generates from its rules catalog (RE4 in the rules repo's
//! `docs/rule-editor-plan.md`): the rule ids, each rule's parameters typed, and what each rule's
//! check hands its texts. The checks themselves stay hand-written. Their dispatch matches on the
//! generated `RuleId`, so a rule added to the catalog fails the build until its check exists, and
//! a measure added to a rule fails it until the check gives one.
//!
//! In `build.rs`, which has `asset-rules` as a build dependency:
//!
//! ```no_run
//! use std::path::{Path, PathBuf};
//!
//! let catalog = Path::new("../../rules-catalog.toml");
//! println!("cargo:rerun-if-changed={}", catalog.display());
//! let code = asset_rules::codegen::generate(catalog, "0.7.0").unwrap_or_else(|why| panic!("{why}"));
//! let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("rules.rs");
//! std::fs::write(out, code).unwrap();
//! ```
//!
//! In the app, which depends on `asset-rules`:
//!
//! ```ignore
//! pub mod rules {
//!     #![allow(dead_code)]
//!     include!(concat!(env!("OUT_DIR"), "/rules.rs"));
//! }
//! ```
//!
//! For a catalog with `texture.max_size` (parameter `max`, measures `width` and `height`) and
//! `texture.format` (a case, `unity_cant_read`), that module holds:
//! - `CATALOG_TOML`, the catalog's text, and `catalog()`, the catalog read once;
//! - `RuleId`, a variant per rule in catalog order (`RuleId::MaxSize`), with `ALL`, `id()`,
//!   `from_id()` and `rule()`, the rule's catalog entry;
//! - `params::MaxSize { max: u32 }`, for each rule with parameters, with `read(&RuleSettings)`;
//! - `found::MaxSize { width: String, height: String }`, for every rule: what its check hands the
//!   texts. A rule with cases also has `case: Option<found::FormatCase>`;
//! - `Found`, a variant per rule, with `rule()`, `case()`, `measures()` and `texts()`, the
//!   finding's texts filled in.

use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

use crate::catalog::{Catalog, Param, ParamKind, RuleSettings};

/// Reads, checks and generates: the Rust code for the catalog at `path`, or every problem in it.
/// `app_version` is the app's own version: no rule may be newer.
pub fn generate(path: &Path, app_version: &str) -> Result<String, String> {
    let shown = path.display();
    let text = std::fs::read_to_string(path).map_err(|error| format!("{shown}: {error}"))?;
    let catalog = Catalog::from_toml(&text).map_err(|error| format!("{shown} {error}"))?;
    let mut problems: Vec<String> = catalog
        .check(Some(app_version))
        .iter()
        .map(ToString::to_string)
        .collect();
    problems.extend(code_problems(&catalog));
    if !problems.is_empty() {
        return Err(format!(
            "{shown} has {} problem{}:\n  {}",
            problems.len(),
            if problems.len() == 1 { "" } else { "s" },
            problems.join("\n  ")
        ));
    }
    let absolute = std::path::absolute(path).unwrap_or_else(|_| path.to_path_buf());
    Ok(rust(&catalog, &absolute.display().to_string()))
}

/// Names the catalog allows that Rust code can't use: keywords that can't be raw identifiers,
/// and a measure called `case` in a rule with cases.
fn code_problems(catalog: &Catalog) -> Vec<String> {
    let mut out = Vec::new();
    for rule in &catalog.rules {
        let names = rule
            .params
            .iter()
            .map(|param| ("param", param.key.as_str()))
            .chain(rule.measures.iter().map(|m| ("measure", m.as_str())));
        for (what, name) in names {
            if NOT_RAW.contains(&name) {
                out.push(format!(
                    "rule \"{}\": {what} \"{name}\" can't be a Rust name",
                    rule.id
                ));
            }
        }
        if !rule.cases.is_empty() && rule.measures.iter().any(|m| m == "case") {
            out.push(format!(
                "rule \"{}\": a rule with cases can't have a measure called \"case\"",
                rule.id
            ));
        }
    }
    out
}

/// The generated code for `catalog`, which `include_str!`s the catalog from `path`: absolute, or
/// relative to the file the code is written to.
pub fn rust(catalog: &Catalog, path: &str) -> String {
    let mut out = String::new();
    let o = &mut out;
    let rules = &catalog.rules;
    line(
        o,
        0,
        &format!(
            "// Generated by asset-rules from {}'s rules catalog: change the catalog, not this.",
            catalog.tool
        ),
    );
    blank(o);
    line(
        o,
        0,
        "/// The rules catalog this was generated from, as written.",
    );
    line(
        o,
        0,
        &format!("pub const CATALOG_TOML: &str = include_str!({path:?});"),
    );
    blank(o);
    line(
        o,
        0,
        "/// The rules catalog, read once. `build.rs` checked it, so reading it can't fail.",
    );
    line(
        o,
        0,
        "pub fn catalog() -> &'static ::asset_rules::catalog::Catalog {",
    );
    line(
        o,
        1,
        "static CATALOG: ::std::sync::OnceLock<::asset_rules::catalog::Catalog> =",
    );
    line(o, 2, "::std::sync::OnceLock::new();");
    line(o, 1, "CATALOG.get_or_init(|| {");
    line(
        o,
        2,
        "::asset_rules::catalog::Catalog::from_toml(CATALOG_TOML).expect(\"build.rs checked it\")",
    );
    line(o, 1, "})");
    line(o, 0, "}");
    blank(o);

    // RuleId.
    line(o, 0, "/// Every rule in the catalog, in its order.");
    line(
        o,
        0,
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]",
    );
    line(o, 0, "#[allow(clippy::enum_variant_names)]");
    line(o, 0, "pub enum RuleId {");
    for rule in rules {
        line(o, 1, &format!("/// `{}`: {}", rule.id, rule.title));
        line(o, 1, &format!("{},", rule.code_name()));
    }
    line(o, 0, "}");
    blank(o);
    line(o, 0, "impl RuleId {");
    line(o, 1, "/// Every rule, in catalog order.");
    line(
        o,
        1,
        &format!("pub const ALL: [RuleId; {}] = [", rules.len()),
    );
    for rule in rules {
        line(o, 2, &format!("RuleId::{},", rule.code_name()));
    }
    line(o, 1, "];");
    blank(o);
    line(o, 1, "/// The id rules files and results use.");
    line(o, 1, "pub const fn id(self) -> &'static str {");
    line(o, 2, "match self {");
    for rule in rules {
        line(
            o,
            3,
            &format!("RuleId::{} => {:?},", rule.code_name(), rule.id),
        );
    }
    line(o, 2, "}");
    line(o, 1, "}");
    blank(o);
    line(o, 1, "/// The rule a rules file or results name by `id`.");
    line(o, 1, "pub fn from_id(id: &str) -> Option<RuleId> {");
    line(o, 2, "match id {");
    for rule in rules {
        line(
            o,
            3,
            &format!("{:?} => Some(RuleId::{}),", rule.id, rule.code_name()),
        );
    }
    line(o, 3, "_ => None,");
    line(o, 2, "}");
    line(o, 1, "}");
    blank(o);
    line(o, 1, "/// The rule's entry in the catalog.");
    line(
        o,
        1,
        "pub fn rule(self) -> &'static ::asset_rules::catalog::Rule {",
    );
    line(o, 2, "&catalog().rules[self as usize]");
    line(o, 1, "}");
    line(o, 0, "}");
    blank(o);

    // params.
    line(
        o,
        0,
        "/// Each rule's parameters, typed, for the rules that have any.",
    );
    line(o, 0, "pub mod params {");
    let mut first = true;
    for rule in rules.iter().filter(|rule| !rule.params.is_empty()) {
        if !first {
            blank(o);
        }
        first = false;
        let name = rule.code_name();
        line(o, 1, &format!("/// `{}`'s parameters.", rule.id));
        line(o, 1, "#[derive(Clone, Debug, PartialEq)]");
        line(o, 1, &format!("pub struct {name} {{"));
        for param in &rule.params {
            line(o, 2, &format!("/// {}", param.label));
            line(
                o,
                2,
                &format!("pub {}: {},", ident(&param.key), param_type(param)),
            );
        }
        line(o, 1, "}");
        blank(o);
        line(o, 1, &format!("impl {name} {{"));
        line(
            o,
            2,
            "/// Reads them from the rule's settings, which `Rule::settings` keeps valid.",
        );
        line(
            o,
            2,
            &format!("pub fn read(settings: &::asset_rules::catalog::RuleSettings) -> {name} {{"),
        );
        line(o, 3, &format!("{name} {{"));
        for param in &rule.params {
            line(
                o,
                4,
                &format!(
                    "{}: ::asset_rules::codegen::param(settings, {:?}),",
                    ident(&param.key),
                    param.key
                ),
            );
        }
        line(o, 3, "}");
        line(o, 2, "}");
        line(o, 1, "}");
    }
    line(o, 0, "}");
    blank(o);

    // found.
    line(
        o,
        0,
        "/// What each rule's check found, for its texts: the values they name, and the case.",
    );
    line(o, 0, "pub mod found {");
    for (i, rule) in rules.iter().enumerate() {
        if i > 0 {
            blank(o);
        }
        let name = rule.code_name();
        let has_case = !rule.cases.is_empty();
        if !has_case && rule.measures.is_empty() {
            line(
                o,
                1,
                &format!(
                    "/// What `{}`'s check found: nothing its texts name.",
                    rule.id
                ),
            );
            line(o, 1, "#[derive(Clone, Debug, PartialEq)]");
            line(o, 1, &format!("pub struct {name};"));
            continue;
        }
        line(o, 1, &format!("/// What `{}`'s check found.", rule.id));
        line(o, 1, "#[derive(Clone, Debug, PartialEq)]");
        line(o, 1, &format!("pub struct {name} {{"));
        if has_case {
            line(o, 2, "/// The texts' case, or `None` for the rule's own.");
            line(o, 2, &format!("pub case: Option<{name}Case>,"));
        }
        for measure in &rule.measures {
            line(o, 2, &format!("pub {}: String,", ident(measure)));
        }
        line(o, 1, "}");
        if has_case {
            blank(o);
            line(o, 1, &format!("/// `{}`'s cases.", rule.id));
            line(o, 1, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
            line(o, 1, &format!("pub enum {name}Case {{"));
            for case in rule.cases.keys() {
                line(o, 2, &format!("{},", camel(case)));
            }
            line(o, 1, "}");
            blank(o);
            line(o, 1, &format!("impl {name}Case {{"));
            line(o, 2, "/// The case's name in the catalog.");
            line(o, 2, "pub const fn name(self) -> &'static str {");
            line(o, 3, "match self {");
            for case in rule.cases.keys() {
                line(o, 4, &format!("{name}Case::{} => {case:?},", camel(case)));
            }
            line(o, 3, "}");
            line(o, 2, "}");
            line(o, 1, "}");
        }
    }
    line(o, 0, "}");
    blank(o);

    // Found.
    line(o, 0, "/// What one rule's check found.");
    line(o, 0, "#[derive(Clone, Debug, PartialEq)]");
    line(
        o,
        0,
        "#[allow(clippy::enum_variant_names, clippy::large_enum_variant)]",
    );
    line(o, 0, "pub enum Found {");
    for rule in rules {
        let name = rule.code_name();
        line(o, 1, &format!("{name}(found::{name}),"));
    }
    line(o, 0, "}");
    blank(o);
    line(o, 0, "impl Found {");
    line(o, 1, "pub fn rule(&self) -> RuleId {");
    line(o, 2, "match self {");
    for rule in rules {
        let name = rule.code_name();
        line(o, 3, &format!("Found::{name}(_) => RuleId::{name},"));
    }
    line(o, 2, "}");
    line(o, 1, "}");
    blank(o);
    line(
        o,
        1,
        "/// The case the texts take, by its catalog name, or `None` for the rule's own.",
    );
    line(o, 1, "pub fn case(&self) -> Option<&'static str> {");
    line(o, 2, "match self {");
    for rule in rules {
        let name = rule.code_name();
        if rule.cases.is_empty() {
            line(o, 3, &format!("Found::{name}(_) => None,"));
        } else {
            line(
                o,
                3,
                &format!("Found::{name}(inner) => inner.case.map(found::{name}Case::name),"),
            );
        }
    }
    line(o, 2, "}");
    line(o, 1, "}");
    blank(o);
    line(o, 1, "/// The values the texts name, by measure.");
    line(
        o,
        1,
        "pub fn measures(&self) -> ::std::collections::BTreeMap<&'static str, String> {",
    );
    line(o, 2, "match self {");
    for rule in rules {
        let name = rule.code_name();
        if rule.measures.is_empty() {
            line(
                o,
                3,
                &format!("Found::{name}(_) => ::std::collections::BTreeMap::new(),"),
            );
            continue;
        }
        line(
            o,
            3,
            &format!("Found::{name}(inner) => ::std::collections::BTreeMap::from(["),
        );
        for measure in &rule.measures {
            line(
                o,
                4,
                &format!("({measure:?}, inner.{}.clone()),", ident(measure)),
            );
        }
        line(o, 3, "]),");
    }
    line(o, 2, "}");
    line(o, 1, "}");
    blank(o);
    line(
        o,
        1,
        "/// The finding's texts: the rule's, `base`'s and the case's, with the parameters in",
    );
    line(o, 1, "/// `settings` and the measures filled in.");
    line(o, 1, "pub fn texts(");
    line(o, 2, "&self,");
    line(o, 2, "base: Option<&str>,");
    line(o, 2, "settings: &::asset_rules::catalog::RuleSettings,");
    line(o, 1, ") -> ::asset_rules::catalog::FindingTexts {");
    line(o, 2, "let rule = self.rule().rule();");
    line(
        o,
        2,
        "rule.fill_texts(&rule.texts(base, self.case()), settings, &self.measures())",
    );
    line(o, 1, "}");
    line(o, 0, "}");
    for rule in rules {
        let name = rule.code_name();
        blank(o);
        line(o, 0, &format!("impl From<found::{name}> for Found {{"));
        line(o, 1, &format!("fn from(inner: found::{name}) -> Found {{"));
        line(o, 2, &format!("Found::{name}(inner)"));
        line(o, 1, "}");
        line(o, 0, "}");
    }
    out
}

/// Reads one parameter as the type the generated code gives it. For generated code.
#[doc(hidden)]
pub trait FromParam: Sized {
    fn from_param(value: &Value) -> Option<Self>;
}

impl FromParam for u32 {
    fn from_param(value: &Value) -> Option<u32> {
        i64::from_param(value).and_then(|n| u32::try_from(n).ok())
    }
}

impl FromParam for u64 {
    fn from_param(value: &Value) -> Option<u64> {
        value
            .as_u64()
            .or_else(|| i64::from_param(value).and_then(|n| u64::try_from(n).ok()))
    }
}

/// Also a whole number written `6.0`.
impl FromParam for i64 {
    fn from_param(value: &Value) -> Option<i64> {
        value.as_i64().or_else(|| {
            let n = value.as_f64()?;
            (n.fract() == 0.0 && n.abs() < 9.0e15).then_some(n as i64)
        })
    }
}

impl FromParam for f64 {
    fn from_param(value: &Value) -> Option<f64> {
        value.as_f64()
    }
}

impl FromParam for bool {
    fn from_param(value: &Value) -> Option<bool> {
        value.as_bool()
    }
}

impl FromParam for String {
    fn from_param(value: &Value) -> Option<String> {
        value.as_str().map(str::to_owned)
    }
}

impl<T: FromParam> FromParam for Vec<T> {
    fn from_param(value: &Value) -> Option<Vec<T>> {
        value.as_array()?.iter().map(T::from_param).collect()
    }
}

/// The parameter `key` of `settings`, as `T`. [`Rule::settings`](crate::catalog::Rule::settings)
/// keeps every value valid and
/// [`Catalog::check`] every default, so the fallback (`T::default()`) is never used.
#[doc(hidden)]
pub fn param<T: FromParam + Default>(settings: &RuleSettings, key: &str) -> T {
    settings
        .params
        .get(key)
        .and_then(T::from_param)
        .unwrap_or_default()
}

/// The Rust type of a parameter's value.
fn param_type(param: &Param) -> String {
    match param.kind {
        ParamKind::Count => whole_type(param.min, param.max).to_owned(),
        ParamKind::Number => "f64".to_owned(),
        ParamKind::Flag => "bool".to_owned(),
        ParamKind::Choice => option_type(param).to_owned(),
        ParamKind::Choices => format!("Vec<{}>", option_type(param)),
        ParamKind::Patterns => "Vec<String>".to_owned(),
    }
}

/// `u32` for a whole number from 0 to `u32::MAX`, `u64` for one from 0 up, else `i64`.
fn whole_type(min: Option<f64>, max: Option<f64>) -> &'static str {
    match (min, max) {
        (Some(min), Some(max)) if min >= 0.0 && max <= f64::from(u32::MAX) => "u32",
        (Some(min), _) if min >= 0.0 => "u64",
        _ => "i64",
    }
}

/// The type of a choice's options: text, whole numbers, or numbers.
fn option_type(param: &Param) -> &'static str {
    let values: Vec<&Value> = param.options.iter().map(|o| &o.value).collect();
    if values.iter().all(|v| v.is_string()) {
        return "String";
    }
    let whole: Option<Vec<i64>> = values.iter().map(|v| v.as_i64()).collect();
    match whole {
        Some(whole) => {
            let min = whole.iter().copied().min().unwrap_or(0) as f64;
            let max = whole.iter().copied().max().unwrap_or(0) as f64;
            whole_type(Some(min), Some(max))
        }
        None => "f64",
    }
}

/// `unity_cant_read` → `UnityCantRead`.
fn camel(name: &str) -> String {
    name.split('_')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().chain(chars).collect::<String>(),
                None => String::new(),
            }
        })
        .collect()
}

/// A lowercase word as a Rust identifier: a keyword becomes a raw identifier.
fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

/// Rust's keywords, strict and reserved, in lowercase.
const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where",
    "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "try",
    "typeof", "unsized", "virtual", "yield",
];

/// Keywords that can't be raw identifiers either.
const NOT_RAW: &[&str] = &["crate", "self", "super"];

fn line(out: &mut String, indent: usize, text: &str) {
    let _ = writeln!(out, "{}{text}", "    ".repeat(indent));
}

fn blank(out: &mut String) {
    out.push('\n');
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert_eq!(camel("unity_cant_read"), "UnityCantRead");
        assert_eq!(ident("type"), "r#type");
        assert_eq!(ident("width"), "width");
    }

    #[test]
    fn types() {
        assert_eq!(whole_type(Some(1.0), Some(16384.0)), "u32");
        assert_eq!(whole_type(Some(0.0), None), "u64");
        assert_eq!(whole_type(None, Some(10.0)), "i64");
        assert_eq!(whole_type(Some(-5.0), Some(5.0)), "i64");
    }
}
